def mask(w,h,label):
    lines=[]
    for para in label.upper().split('\n'):
        line=''
        for word in para.split():
            candidate=(line+' '+word).strip()
            if len(candidate)*6-1>w and line:lines.append(line);line=word
            else:line=candidate
        if line:lines.append(line)
    assert lines and max(len(s)*6-1 for s in lines)<=w,(label,w)
    total=8*len(lines)-1
    assert total<=h,(label,w,h)
    im=Image.new('L',(w,h))
    for row,line in enumerate(lines):
        x=(w-(len(line)*6-1))//2;y=(h-total)//2+row*8
        for n,c in enumerate(line):
            for yy,bits in enumerate(ROWS[c].split('/')):
                for xx,bit in enumerate(bits):
                    if bit=='1':im.putpixel((x+n*6+xx,y+yy),255)
    return im


def label(im,box,text,fg,bg):
    x,y,w,h=box
    m=mask(w,h,text)
    im.paste(bg,(x,y,x+w,y+h))
    im.paste(fg,(x,y,x+w,y+h),m)
